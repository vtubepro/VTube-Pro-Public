"""Bases for Pro2D -> 3D: VTube Pro's own bundled base bodies (Mirelle, Kairo) and the performer's own base.

    python blender/to3d/user_base.py check <file.vrm>      -> one JSON line: {ok, kind, base, gender, problems, metrics}
    python blender/to3d/user_base.py builtins [--write]    -> measure the bundled bases into builtin_bases.json

The bundled bases are the sample avatars that ship with the helper (assets/builtin/mirelle, assets/builtin/kairo:
VTube Pro's own, built from the CC0 VRoid classic samples with face_kit). Their VRM holds the body with its default
outfit and hair; costumes and the headset are separate files and never part of the base. Nothing is downloaded.
A user's own base must be a VRoid-made VRM 0.x (the face kit repaints VRoid's face texture and drives its Fcl_* face
shapes): humanoid bones (hips ... head, both eyes), a mesh named Face with its expressions, the EyeIris / EyeWhite
parts. Every base is measured the way design.BASE_METRICS was (eye width / height, IPD, eye line -> chin, iris share,
cheek and jaw widths), so the design fits the drawing to it. builtin_bases.json is GENERATED by `builtins --write`
(tools/to3d_pipeline_test.py checks it matches the shipped files): never hand-edited.
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.append(os.path.dirname(HERE))

# the bundled bases: key -> (avatar folder, model file, gender)
BUILTIN = {'mirelle': ('mirelle', 'mirelle.vrm', 'female'), 'kairo': ('kairo', 'kairo.vrm', 'male')}
BUILTIN_JSON = os.path.join(HERE, 'builtin_bases.json')


def builtin_file(key):
    d, f, _g = BUILTIN[key]
    return os.path.join(ROOT, 'assets', 'builtin', d, f)


def load_builtins():
    """{key: {file, gender, sha256, metrics, aspect, col_aspect}} for the bundled bases present in this install"""
    try:
        with open(BUILTIN_JSON, encoding='utf-8') as f:
            table = json.load(f)['bases']
    except (OSError, ValueError, KeyError):
        return {}
    out = {}
    for k, v in table.items():
        p = builtin_file(k) if k in BUILTIN else None
        if p and os.path.isfile(p):
            out[k] = dict(v, file=p)
    return out


def register_builtins():
    """register the bundled bases (builtin_bases.json) as anime_creator bases with their measurements, for the pipeline
    and the references; returns their keys (the only bases a Pro2D conversion picks from)"""
    from anime_creator import params as CP
    from live2d import design as D, faceadj as FA
    keys = []
    for k, b in load_builtins().items():
        CP.BASES[k] = {'file': b['file'], 'gender': b['gender'], 'label': k}
        D.BASE_METRICS[k] = {m: v for m, v in b['metrics'].items() if v is not None}
        FA.BASE_ASPECT[k] = b['aspect']
        FA.BASE_COL_ASPECT[k] = b['col_aspect']
        keys.append(k)
    return keys


def measure_builtins():
    out = {}
    for k in BUILTIN:
        p = builtin_file(k)
        if not os.path.isfile(p):
            continue
        c = check(p)
        if not c['ok']:
            raise SystemExit(f'bundled base {k} is not usable: {c["problems"]}')
        M = c['metrics']
        aspect = M['eye_h'] / M['eye_w']
        # the eye opening's aspect (faceadj.BASE_ASPECT) and its column height (BASE_COL_ASPECT: ~0.93 of it on the
        # VRoid eyes: shino 0.729 / 0.768, fumiriya 0.601 / 0.661)
        out[k] = {'gender': BUILTIN[k][2], 'sha256': c['sha256'], 'metrics': M, 'aspect': round(aspect, 3), 'col_aspect': round(0.93 * aspect, 3)}
    return {'format': 'vtp.to3d-bases/1', 'bases': out}


NEEDED_BONES = ('hips', 'spine', 'chest', 'neck', 'head', 'leftEye', 'rightEye', 'leftUpperArm', 'rightUpperArm',
                'leftUpperLeg', 'rightUpperLeg')


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def identify(digest):
    """which bundled base this file is (None = the user's own)"""
    for k in BUILTIN:
        p = builtin_file(k)
        if os.path.isfile(p) and digest == sha256(p):
            return k
    return None


def check(path):
    out = {'ok': False, 'kind': None, 'base': None, 'gender': None, 'problems': [], 'metrics': None, 'title': None}
    try:
        import numpy as np  # noqa: F401
        from anime_creator.vroid import Model
        m = Model(path)
    except Exception as e:
        out['problems'].append(f'This file could not be read as a VRM ({type(e).__name__}).')
        return out
    J = m.J
    ext = J.get('extensions', {})
    if 'VRM' not in ext:
        if 'VRMC_vrm' in ext:
            out['problems'].append('This is a VRM 1.0 file. In VRoid Studio, export it again as VRM 0.0.')
        else:
            out['problems'].append('This is not a VRM file made in VRoid Studio.')
        return out
    meta = ext['VRM'].get('meta', {})
    out['title'] = meta.get('title')
    digest = sha256(path)
    out['sha256'] = digest
    base = identify(digest)
    out['kind'] = 'builtin' if base else 'user'
    out['base'] = base or 'user'
    human = {b.get('bone'): b.get('node') for b in ext['VRM'].get('humanoid', {}).get('humanBones', [])}
    miss = [b for b in NEEDED_BONES if b not in human]
    if miss:
        out['problems'].append('It is missing body bones (' + ', '.join(miss[:4]) + '). Use a model made in VRoid Studio.')
    if m.mesh_index('Face') is None:
        out['problems'].append('It has no face mesh named "Face". Use a model made in VRoid Studio.')
    else:
        d = m.read_mesh(m.mesh_index('Face'))
        names = list(d.target_names)
        if not any('Fcl_' in n for n in names):
            out['problems'].append('Its face has no VRoid expressions (Fcl_ shapes). Export it again from VRoid Studio.')
        mats = ' '.join(m.mat_name(p['material']) for p in d.prims)
        if 'EyeIris' not in mats or 'EyeWhite' not in mats:
            out['problems'].append('Its eyes are not VRoid eyes (EyeIris / EyeWhite). Use a model made in VRoid Studio.')
    if out['problems']:
        return out
    out['gender'] = BUILTIN[base][2] if base else None
    try:
        out['metrics'] = metrics(m)
    except Exception as e:
        out['problems'].append(f'Its face could not be measured ({e}). Use a model made in VRoid Studio.')
        return out
    out['ok'] = True
    return out


def metrics(m):
    """the face measured like design.BASE_METRICS (metres, from face_kit's own landmarks)"""
    import numpy as np
    from face_kit.vroid_face import VFace
    vf = VFace(m, log=lambda s: None)
    e0, e1 = vf.eyes
    ipd = abs(e1.cx - e0.cx)
    iris_rx = float(np.mean([i['rx'] for i in vf.irises]))
    iris_ry = float(np.mean([i['ry'] for i in vf.irises]))
    d = vf.d
    skin = [i for i, p in enumerate(d.prims) if m.mat_name(p['material']).upper().endswith('_SKIN')] or list(range(len(d.prims)))
    P = d.P[d.verts_of(skin)]

    def width_at(y):
        band = P[np.abs(P[:, 1] - y) < 0.004]
        return float(np.ptp(band[:, 0])) if len(band) > 3 else None
    def part(name):
        ids = [i for i, p in enumerate(d.prims) if name in m.mat_name(p['material'])]
        return d.P[d.verts_of(ids)] if ids else None
    W, B = part('EyeWhite'), part('FaceBrow')
    side = W[W[:, 0] < 0] if (W[:, 0] < 0).any() else W
    eye_w, eye_h = float(np.ptp(side[:, 0])), float(np.ptp(side[:, 1]))       # the eye WHITE, as BASE_METRICS
    brow_gap = float(B[:, 1].mean() - W[:, 1].mean()) if B is not None else 0.42 * ipd
    eye_chin = vf.eye_y - vf.chin_y
    mid = width_at(vf.eye_y - 0.5 * eye_chin)
    low = width_at(vf.eye_y - 0.8 * eye_chin)
    tilt = float(np.mean([abs(e.corner_out[1] - e.corner_in[1]) / max(2 * e.ew, 1e-6) for e in vf.eyes]))
    return {'eye_w': round(eye_w, 4), 'eye_h': round(eye_h, 4), 'ipd': round(ipd, 4), 'eye_chin': round(eye_chin, 4),
            'brow_gap': round(brow_gap, 4), 'eye_tilt': round(tilt, 3), 'iris_ratio': round(iris_rx / max(vf.ew, 1e-6), 3),
            'iris_aspect': round(iris_ry / max(iris_rx, 1e-6), 3),
            'fw_mid': round(mid / ipd, 3) if mid else None, 'fw_low': round(low / ipd, 3) if low else None}


if __name__ == '__main__':
    import numpy  # noqa: F401  (before blender/ shadows inspect)
    if len(sys.argv) >= 3 and sys.argv[1] == 'check':
        print(json.dumps(check(sys.argv[2])))
        sys.exit(0)
    if len(sys.argv) >= 2 and sys.argv[1] == 'builtins':
        t = measure_builtins()
        if '--write' in sys.argv:
            with open(BUILTIN_JSON, 'w', encoding='utf-8', newline='\n') as f:
                json.dump(t, f, indent=1)
                f.write('\n')
        print(json.dumps(t))
        sys.exit(0)
    print('usage: user_base.py check <file.vrm> | builtins [--write]')
    sys.exit(2)
